import { describe, expect, it } from "vitest";

import {
  parseStaffAccessToken,
  parseStaffLogin,
  parseStaffRevalidation,
  parseTenantSlug
} from "./staff-auth-input.js";

describe("staff authentication input", () => {
  it("accepts only the opaque bearer token format generated by the API", () => {
    const token = "a".repeat(43);
    expect(parseStaffAccessToken(`Bearer ${token}`)).toBe(token);
    expect(() => parseStaffAccessToken(undefined)).toThrow("Sesión inválida.");
    expect(() => parseStaffAccessToken("Basic abc")).toThrow(
      "Sesión inválida."
    );
    expect(() => parseStaffAccessToken("Bearer too-short")).toThrow(
      "Sesión inválida."
    );
  });

  it("validates the PIN used for sensitive revalidation", () => {
    expect(parseStaffRevalidation({ pin: "194827" })).toEqual({
      pin: "194827"
    });
    expect(() => parseStaffRevalidation({ pin: "19482" })).toThrow(
      "PIN inválido."
    );
  });

  it("normalizes a valid username", () => {
    expect(
      parseStaffLogin({ pin: "194827", username: "  Ana.Moza  " })
    ).toEqual({ pin: "194827", username: "ana.moza" });
  });

  it.each([
    null,
    {},
    { pin: "12345", username: "ana" },
    { pin: "123456", username: "a!" },
    { pin: "123456", username: "ana pérez" }
  ])("rejects malformed login input", (input) => {
    expect(() => parseStaffLogin(input)).toThrow("Datos de acceso inválidos.");
  });

  it("accepts only canonical tenant slugs", () => {
    expect(parseTenantSlug("restaurante-demo")).toBe("restaurante-demo");
    expect(() => parseTenantSlug("Restaurante Demo")).toThrow(
      "Negocio inválido."
    );
  });
});
